case "$ACTION" in
  start)
    # 手动启动 = 我确实想让它跑，清掉守护的停机标记
    rm -f "$HOLD_FILE"
    start_napcat || exit 1
    start_bridge || exit 1
    # 启守护：有它才有 15 分钟级外部自愈；起不来只警告，不假装已就绪。
    ensure_guard || true
    ;;
  bridge|bridge-restart|restart-bridge)
    restart_bridge_only
    ;;
  stop)
    # 落停机标记：否则守护进程会在 30 秒内把它重新拉起来（"闹鬼"）
    : >"$HOLD_FILE"
    if guard_running; then
      bash "$GUARD_SCRIPT" stop >/dev/null 2>&1 || true
    fi
    stop_all
    ;;
  restart)
    printf '⚠️ restart 会同时重启 NapCat，可能丢失当前登录态；只重启桥接器请用 restart-bridge。\n' >&2
    rm -f "$HOLD_FILE"
    if guard_running; then bash "$GUARD_SCRIPT" stop >/dev/null 2>&1 || true; fi
    stop_all; sleep 2
    start_napcat || exit 1
    start_bridge || exit 1
    ensure_guard || true
    ;;
  status)
    rc=0
    if napcat_running; then printf 'NapCat:   运行中 (screen %s)\n' "$SCREEN_NAME"; else printf 'NapCat:   未运行\n'; rc=1; fi
    if [ -n "$NAPCAT_QQ_ID" ]; then
      printf '登录方式: 快速登录 %s（重启后能自动上线）\n' "$(mask_id "$NAPCAT_QQ_ID")"
    else
      printf '登录方式: 扫码——**未配置快速登录，重启后必须人工扫码**\n'
      printf '          修复：echo <QQ号> > %s/qq-account\n' "$RUNTIME_DIR"
    fi
    if bridge_running; then printf '桥接器:   运行中 (pid %s)\n' "$(cat "$BRIDGE_PID_FILE")"; else printf '桥接器:   未运行\n'; rc=1; fi
    if guard_running; then printf '守护:     运行中 (pid %s)\n' "$(cat "$GUARD_PID_FILE")"; else printf '守护:     未运行（外部自愈不工作）\n'; fi
    printf '定时任务: %s\n' "$(guard_job_line)"
    printf '守护心跳: %s\n' "$(guard_health_line)"
    live="$(live_connected)"
    if ! bridge_running; then
      printf 'OneBot:   未知（桥接器未运行，不读僵尸状态）\n'
    elif [ "$live" = 1 ]; then
      printf 'OneBot:   已连接（%s 端口在监听）\n' "$ONEBOT_PORT"
    elif [ "$live" = 0 ]; then
      printf 'OneBot:   未连接（QQ 未登录/掉线；%s 端口%s）\n' "$ONEBOT_PORT" "$(onebot_listening && echo 在监听 || echo 未监听)"
    else
      printf 'OneBot:   未知（管理接口 /status 读不到）\n'
    fi
    # 僵尸真相：进程死了，status.json 仍可能写着 connected=true；必须标明过期。
    if [ -f "$RUNTIME_DIR/status.json" ]; then
      age="$(status_file_age 2>/dev/null || echo '')"
      if ! bridge_running; then
        printf '状态文件: 过期（桥接器未运行，旧状态不可信）\n'
      elif [ -n "$age" ] && [ "$age" -gt 120 ]; then
        printf '状态文件: 过期（最后更新 %ss 前）\n' "$age"
      fi
    fi
    printf '仪表盘:   %s' "$(panel_url)"
    bridge_running && printf '\n' || printf '（桥接器未运行，暂时没有内容）\n'
    printf 'WebUI:    http://127.0.0.1:%s/webui（token 用 tinda qq webui 查看，不在 status 里打印）\n' "$WEBUI_PORT"
    exit "$rc"
    ;;
  logs)
    touch "$BRIDGE_LOG"; tail -n 100 -f "$BRIDGE_LOG"
    ;;
  webui) webui_url ;;
  web) cmd_web ;;
  doctor) cmd_doctor ;;
  qrcode) qrcode ;;
  nlogs)
    touch "$NAPCAT_LOG"; tail -n 120 -f "$NAPCAT_LOG"
    ;;
  *)
    printf '用法: %s {start|stop|restart|bridge|status|doctor|logs|nlogs|webui|web|qrcode}\n' "$0" >&2
    exit 2
    ;;
esac
