# tinda qq web —— 打开/打印只读仪表盘
cmd_web() {
  local url
  url="$(panel_url)"
  if ! bridge_running; then
    printf '桥接器未运行，仪表盘不会有内容。\n' >&2
    printf '先启动：%s start\n' "$0" >&2
    printf '（配置好的地址会是：%s）\n' "$url" >&2
    return 1
  fi
  # 端口被占/面板启动失败时，panel.url 不存在或已过期；只有真的能访问才打印。
  if ! url_reachable "$url"; then
    printf '仪表盘不可用：%s 无法访问（面板端口被占用或面板启动失败）。\n' "$url" >&2
    printf '看桥接器日志：%s\n' "$BRIDGE_LOG" >&2
    return 1
  fi
  printf '%s\n' "$url"
  # 有图形环境就顺手打开；没有就只打印（Termux 是纯终端）
  case "${TINDA_QQ_OPEN:-}" in
    1) command -v termux-open-url >/dev/null 2>&1 && termux-open-url "$url" >/dev/null 2>&1 || true ;;
  esac
  return 0
}

# tinda qq doctor：只读体检；不启停、不打印 token。
cmd_doctor() {
  if [ ! -r "$BRIDGE_DIR/tools/doctor.js" ]; then
    printf '找不到体检脚本：%s\n' "$BRIDGE_DIR/tools/doctor.js" >&2
    return 1
  fi
  node "$BRIDGE_DIR/tools/doctor.js" \
    --bridge "$BRIDGE_DIR" --config "$BRIDGE_DIR/config.json" --state "$RUNTIME_DIR"
}

